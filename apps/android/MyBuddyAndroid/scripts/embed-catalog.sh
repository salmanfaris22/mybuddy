#!/usr/bin/env bash
# Regenerates EventCatalogData.kt from protocol/schema/events.v1.json (Kotlin raw string, `$` escaped).
# A unit test fails if the embedded copy drifts from the shared file.
set -euo pipefail
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../../../.." && pwd)"
SRC="$ROOT/protocol/schema/events.v1.json"
OUT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)/app/src/main/java/app/mybuddy/android/core/protocol/EventCatalogData.kt"
{
  echo "// GENERATED by scripts/embed-catalog.sh from protocol/schema/events.v1.json — do not edit."
  echo "package app.mybuddy.android.core.protocol"
  echo ""
  echo "internal object EventCatalogData {"
  printf '    val JSON: String = """'
  sed "s/\\\$/\${'\$'}/g" "$SRC"
  printf '"""\n}\n'
} > "$OUT"
echo "wrote $OUT"

import CryptoKit
import Foundation
import Testing
@testable import MyBuddyCore

@Suite("MBH1 secure channel")
struct MBH1Tests {
    let v: Vectors
    let host: SoftwareIdentity
    let client: SoftwareIdentity

    init() throws {
        v = try Vectors.load()
        host = try SoftwareIdentity(rawScalar: v.hex("hostIdentityPrivateScalarHex"))
        client = try SoftwareIdentity(rawScalar: v.hex("clientIdentityPrivateScalarHex"))
    }

    var hostEphemeral: P256.KeyAgreement.PrivateKey { try! .init(rawRepresentation: v.hex("hostEphemeralPrivateScalarHex")) }
    var clientEphemeral: P256.KeyAgreement.PrivateKey { try! .init(rawRepresentation: v.hex("clientEphemeralPrivateScalarHex")) }

    // MARK: Cross-language vectors (generated by Go, verified by CryptoKit)

    @Test func identityEncodingMatchesGo() {
        #expect(host.publicKeySPKI == v.b64("hostIdentityKeySpkiB64u"))
        #expect(client.publicKeySPKI == v.b64("clientIdentityKeySpkiB64u"))
        #expect(host.deviceId == v.expect("hostDeviceId"))
        #expect(client.deviceId == v.expect("clientDeviceId"))
        #expect(host.fingerprint == v.expect("hostFingerprint"))
        #expect(hostEphemeral.publicKey.x963Representation == v.b64("hostEphemeralX963B64u"))
        #expect(clientEphemeral.publicKey.x963Representation == v.b64("clientEphemeralX963B64u"))
    }

    @Test func transcriptSignaturesAndKeysMatchVectors() throws {
        let th1 = MBH1.th1(mode: .pair, clientEphemeral: v.b64("clientEphemeralX963B64u"), clientNonce: v.b64("clientNonceB64u"),
                           hostEphemeral: v.b64("hostEphemeralX963B64u"), hostNonce: v.b64("hostNonceB64u"),
                           hostIdentityKey: v.b64("hostIdentityKeySpkiB64u"))
        #expect(Hex.encode(th1) == v.expect("th1Hex"))
        let goHostSig = Base64URL.decode(v.expect("hostSignatureDerB64u"))!
        #expect(IdentityMath.verify(spki: host.publicKeySPKI, message: MBH1.hostSignedMessage(th1: th1), derSignature: goHostSig))

        let th2 = MBH1.th2(th1: th1, clientIdentityKey: client.publicKeySPKI, clientName: v.input("clientName"), platform: v.input("platform"))
        #expect(Hex.encode(th2) == v.expect("th2Hex"))
        let goClientSig = Base64URL.decode(v.expect("clientSignatureDerB64u"))!
        #expect(IdentityMath.verify(spki: client.publicKeySPKI, message: MBH1.clientSignedMessage(th2: th2), derSignature: goClientSig))
        #expect(!IdentityMath.verify(spki: host.publicKeySPKI, message: MBH1.clientSignedMessage(th2: th2), derSignature: goClientSig))

        #expect(Base64URL.encode(MBH1.pairingProof(secret: v.b64("pairingSecretB64u"), th2: th2)) == v.expect("pairingProofB64u"))

        let shared = try clientEphemeral.sharedSecretFromKeyAgreement(with: hostEphemeral.publicKey).withUnsafeBytes { Data($0) }
        #expect(Hex.encode(shared) == v.expect("sharedSecretHex"))
        let keys = MBH1.deriveSession(sharedSecret: shared, th2: th2)
        #expect(keys.c2h.withUnsafeBytes { Hex.encode(Data($0)) } == v.expect("keyC2HHex"))
        #expect(keys.h2c.withUnsafeBytes { Hex.encode(Data($0)) } == v.expect("keyH2CHex"))
        #expect(keys.sas == v.expect("sas"))
        #expect(keys.sessionId == v.expect("sessionId"))

        // Frames are deterministic given key, direction and counter.
        let frames = v.expected["frames"] as! [[String: Any]]
        var c2h = FrameSealer(key: keys.c2h, direction: .clientToHost)
        var h2c = FrameSealer(key: keys.h2c, direction: .hostToClient)
        var hostOpener = FrameOpener(key: keys.c2h, direction: .clientToHost)
        for frame in frames {
            let plaintext = Data((frame["plaintext"] as! String).utf8)
            let expected = Base64URL.decode(frame["frameB64u"] as! String)!
            if frame["direction"] as! String == "c2h" {
                #expect(try c2h.seal(plaintext) == expected)
                #expect(try hostOpener.open(expected) == plaintext)
            } else {
                #expect(try h2c.seal(plaintext) == expected)
            }
        }
    }

    @Test func fullHandshakeWithVectorInputsReproducesSessionKeys() throws {
        var c = MBH1Client(mode: .pair, identity: client, clientName: "Vivo X300", platform: "android",
                           pinnedHostFingerprint: v.expect("hostFingerprint"), pairingSecret: v.b64("pairingSecretB64u"),
                           ephemeral: clientEphemeral, nonce: v.b64("clientNonceB64u"))
        var h = MBH1Host(identity: host, ephemeral: hostEphemeral, nonce: v.b64("hostNonceB64u"))
        let secret = v.b64("pairingSecretB64u")
        let verifier = MBH1Host.Verifier(
            checkPairingProof: { proof, th2 in proof == MBH1.pairingProof(secret: secret, th2: th2) },
            isTrusted: { _ in false })
        let hostMsg = try h.handleHello(c.makeHello())
        let (reply, clientResult) = try c.handleHost(hostMsg)
        let hostResult = try h.handleClient(reply, verifier: verifier)
        #expect(clientResult.keys.sessionId == v.expect("sessionId"))
        #expect(hostResult.keys.sessionId == v.expect("sessionId"))
        #expect(hostResult.keys.sas == v.expect("sas"))
        #expect(hostResult.clientDeviceId == v.expect("clientDeviceId"))
        #expect(clientResult.hostDeviceId == v.expect("hostDeviceId"))
    }

    // MARK: Live handshakes and negative cases

    private func handshake(mode: MBH1.Mode = .pair, pin: String? = nil, clientSecret: Data? = Data(repeating: 7, count: 32),
                           hostSecret: Data = Data(repeating: 7, count: 32), trusted: Bool = false,
                           tamperHost: ((inout Data) -> Void)? = nil) throws -> (MBH1Client.Result, MBH1Host.Result) {
        let hostID = SoftwareIdentity()
        let phone = SoftwareIdentity()
        var c = MBH1Client(mode: mode, identity: phone, clientName: "Vivo X300", platform: "android",
                           pinnedHostFingerprint: pin ?? hostID.fingerprint, pairingSecret: clientSecret)
        var h = MBH1Host(identity: hostID)
        var hostMsg = try h.handleHello(c.makeHello())
        tamperHost?(&hostMsg)
        let (reply, cr) = try c.handleHost(hostMsg)
        let hr = try h.handleClient(reply, verifier: .init(
            checkPairingProof: { proof, th2 in proof == MBH1.pairingProof(secret: hostSecret, th2: th2) },
            isTrusted: { _ in trusted }))
        return (cr, hr)
    }

    @Test func liveHandshakeAgreesOnKeysAndSAS() throws {
        let (c, h) = try handshake()
        #expect(c.keys.sessionId == h.keys.sessionId)
        #expect(c.keys.sas == h.keys.sas && c.keys.sas.count == 6)

        var phone = SecureSession(role: .phone, keys: c.keys)
        var mac = SecureSession(role: .mac, keys: h.keys)
        let request = try phone.seal(.pairingRequest, payload: ["deviceName": .string("Vivo X300"), "platform": .string("android"), "appVersion": .string("0.1.0")])
        let received = try mac.open(request.frame)
        #expect(received.type == .pairingRequest && received.sequence == 1)
        let reply = try mac.seal(.pairingApproved, payload: ["hostDeviceId": .string(String(repeating: "a", count: 32)), "hostName": .string("Mac"), "grantedCapabilities": .array([.string("health.read")])], replyTo: 1)
        #expect(try phone.open(reply.frame).replyTo == 1)
        // Replaying a frame is fatal.
        #expect(throws: SessionError.frame(.unexpectedCounter(expected: 1, got: 0))) { try mac.open(request.frame) }
    }

    @Test func pinnedFingerprintMismatchIsRejected() {
        #expect(throws: HandshakeError.hostKeyMismatch) {
            _ = try handshake(pin: SoftwareIdentity().fingerprint)
        }
    }

    @Test func tamperedHostSignatureIsRejected() {
        #expect(throws: HandshakeError.badHostSignature) {
            _ = try handshake(tamperHost: { data in
                var obj = try! JSONSerialization.jsonObject(with: data) as! [String: String]
                obj["hostNonce"] = Base64URL.encode(Data(repeating: 1, count: 32))
                data = try! JSONSerialization.data(withJSONObject: obj)
            })
        }
    }

    @Test func wrongPairingSecretIsRejected() {
        #expect(throws: HandshakeError.pairingProofInvalid) {
            _ = try handshake(clientSecret: Data(repeating: 9, count: 32))
        }
        #expect(throws: HandshakeError.pairingProofInvalid) {
            _ = try handshake(clientSecret: nil)
        }
    }

    @Test func resumeRequiresTrustedKey() throws {
        #expect(throws: HandshakeError.notTrusted) { _ = try handshake(mode: .resume, clientSecret: nil) }
        let (c, h) = try handshake(mode: .resume, clientSecret: nil, trusted: true)
        #expect(c.keys.sessionId == h.keys.sessionId && h.mode == .resume)
    }

    @Test func framesRejectTamperingWrongKeyAndGaps() throws {
        let key = SymmetricKey(size: .bits256)
        var sealer = FrameSealer(key: key, direction: .clientToHost)
        let f0 = try sealer.seal(Data("zero".utf8))
        let f1 = try sealer.seal(Data("one".utf8))

        var tampered = f0
        tampered[tampered.count - 1] ^= 1
        var opener = FrameOpener(key: key, direction: .clientToHost)
        #expect(throws: FrameError.authenticationFailed) { try opener.open(tampered) }

        var wrongDirection = FrameOpener(key: key, direction: .hostToClient)
        #expect(throws: FrameError.authenticationFailed) { try wrongDirection.open(f0) }

        var gap = FrameOpener(key: key, direction: .clientToHost)
        #expect(throws: FrameError.unexpectedCounter(expected: 0, got: 1)) { try gap.open(f1) }

        var ok = FrameOpener(key: key, direction: .clientToHost)
        #expect(try ok.open(f0) == Data("zero".utf8))
        #expect(try ok.open(f1) == Data("one".utf8))
        #expect(throws: FrameError.truncated) { try ok.open(Data([1, 2, 3])) }
    }

    @Test func handshakeRejectsMalformedMessages() {
        var h = MBH1Host(identity: SoftwareIdentity())
        #expect(throws: HandshakeError.self) { try h.handleHello(Data("not json".utf8)) }
        var h2 = MBH1Host(identity: SoftwareIdentity())
        let badVersion = #"{"type":"hs.hello","protocol":2,"mode":"pair","clientEphemeral":"AA","clientNonce":"AA"}"#
        #expect(throws: HandshakeError.unsupportedProtocol) { try h2.handleHello(Data(badVersion.utf8)) }
        var h3 = MBH1Host(identity: SoftwareIdentity())
        #expect(throws: HandshakeError.wrongState) { try h3.handleClient(Data("{}".utf8), verifier: .init(checkPairingProof: { _, _ in true }, isTrusted: { _ in true })) }
    }
}

#!/usr/bin/env bash
# Regenerates Sources/MyBuddyCore/Protocol/EventCatalogData.swift from the shared
# protocol catalog. A unit test fails if the embedded copy drifts from the file.
set -euo pipefail
PKG="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
SRC="$PKG/../../../protocol/schema/events.v1.json"
OUT="$PKG/Sources/MyBuddyCore/Protocol/EventCatalogData.swift"
{
  echo "// GENERATED by scripts/embed-catalog.sh from protocol/schema/events.v1.json — do not edit."
  echo "enum EventCatalogData {"
  printf '    static let json = #"""\n'
  cat "$SRC"
  printf '"""#\n'
  echo "}"
} > "$OUT"
echo "wrote $OUT"

import Foundation

public enum ClipboardSyncMode: String, Codable, CaseIterable, Sendable {
    case off
    case ask
    case trustedAuto

    public var title: String {
        switch self {
        case .off: "Off"
        case .ask: "Ask every time"
        case .trustedAuto: "Trusted pair auto sync"
        }
    }
}

public struct ClipboardRevision: Codable, Sendable, Equatable {
    public let revisionId: UUID
    public let originDeviceId: String
    public let contentHash: String
    public let size: Int
    public let createdAt: Date

    public init(text: String, originDeviceId: String, now: Date = Date()) {
        revisionId = UUID()
        self.originDeviceId = originDeviceId
        contentHash = ClipboardPolicy.hash(text)
        size = text.utf8.count
        createdAt = now
    }
}

/// Prevents ping-pong: content applied from a peer is never re-offered back.
public struct ClipboardLoopGuard: Sendable {
    private var recentlyApplied: [String] = []
    private let capacity: Int
    public init(capacity: Int = 16) { self.capacity = capacity }

    public mutating func noteApplied(hash: String) {
        recentlyApplied.removeAll { $0 == hash }
        recentlyApplied.append(hash)
        if recentlyApplied.count > capacity { recentlyApplied.removeFirst() }
    }

    public func shouldOffer(hash: String) -> Bool { !recentlyApplied.contains(hash) }
}

public enum ClipboardDecision: Equatable, Sendable {
    case offerAutomatically
    case askUser(reason: String?)
    case skip(reason: String)
}

/// Decides whether a local clipboard change may be offered to the paired device.
public struct ClipboardPolicy: Sendable {
    public static let maxBytes = 65_536

    /// Pasteboard types that password managers use to mark secrets (nspasteboard.org convention).
    public static let concealedTypes: Set<String> = [
        "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword", "de.petermaurer.TransientPasteboardType",
    ]

    public var mode: ClipboardSyncMode
    public var paused: Bool

    public init(mode: ClipboardSyncMode, paused: Bool = false) {
        self.mode = mode
        self.paused = paused
    }

    public static func hash(_ text: String) -> String { Hex.encode(Data(text.utf8).sha256) }

    public func evaluate(text: String, pasteboardTypes: Set<String>, loopGuard: ClipboardLoopGuard) -> ClipboardDecision {
        guard mode != .off else { return .skip(reason: "Clipboard sync is off") }
        guard !paused else { return .skip(reason: "Clipboard sync is paused") }
        guard pasteboardTypes.isDisjoint(with: Self.concealedTypes) else {
            return .skip(reason: "Marked as a password or secret by the source app")
        }
        guard !text.isEmpty else { return .skip(reason: "Empty") }
        guard text.utf8.count <= Self.maxBytes else { return .skip(reason: "Larger than 64 KB — use file transfer") }
        guard loopGuard.shouldOffer(hash: Self.hash(text)) else { return .skip(reason: "Just received from the paired device") }
        if let why = Self.looksSensitive(text) {
            // Never auto-sync something that looks like a credential; the user may still send it explicitly.
            return .askUser(reason: why)
        }
        return mode == .trustedAuto ? .offerAutomatically : .askUser(reason: nil)
    }

    /// Heuristics for credential-like text. Conservative: false positives only cost a confirmation.
    public static func looksSensitive(_ text: String) -> String? {
        if text.contains("-----BEGIN") && text.contains("PRIVATE KEY") { return "Looks like a private key" }
        let patterns = [
            #"\bsk-[A-Za-z0-9_-]{16,}"#, #"\bsk-ant-[A-Za-z0-9_-]{16,}"#, #"\bgh[pousr]_[A-Za-z0-9]{20,}"#,
            #"\bAKIA[0-9A-Z]{16}\b"#, #"\bxox[abpr]-[A-Za-z0-9-]{10,}"#, #"\beyJ[A-Za-z0-9_-]{10,}\.[A-Za-z0-9_-]{10,}\."#,
        ]
        for p in patterns where text.range(of: p, options: .regularExpression) != nil {
            return "Looks like an API key or token"
        }
        return nil
    }
}
